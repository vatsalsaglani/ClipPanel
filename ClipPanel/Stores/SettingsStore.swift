import Foundation
import Observation

enum PanelAnchor: String, CaseIterable, Sendable {
    case mousePointer
    case screenCenter
    case textCaret

    var title: String {
        switch self {
        case .mousePointer: "Mouse Pointer"
        case .screenCenter: "Screen Center"
        case .textCaret: "Text Caret (Accessibility)"
        }
    }
}

enum MonitoringPauseDuration: TimeInterval, CaseIterable {
    case fifteenMinutes = 900
    case oneHour = 3600
    case fourHours = 14400

    var title: String {
        switch self {
        case .fifteenMinutes: "15 Minutes"
        case .oneHour: "1 Hour"
        case .fourHours: "4 Hours"
        }
    }
}

struct SettingsValidation: Sendable {
    static let historyRange = 1...10_000
    static let payloadRange = 1_024...(200 * 1_024 * 1_024)
    static let pasteDelayRange = 0.03...0.50

    static func historyLimit(_ value: Int) -> Int { min(max(value, historyRange.lowerBound), historyRange.upperBound) }
    static func historyMaximumAgeDays(_ value: Int) -> Int { min(max(value, 0), 3650) }
    static func maximumPayloadBytes(_ value: Int) -> Int { min(max(value, payloadRange.lowerBound), payloadRange.upperBound) }
    static func pasteDelay(_ value: Double) -> Double { value.isNaN ? 0.10 : min(max(value, pasteDelayRange.lowerBound), pasteDelayRange.upperBound) }
}

@MainActor
@Observable
final class SettingsStore {
    private enum Key {
        static let monitoringEnabled = "monitoringEnabled"
        static let monitoringPausedUntil = "monitoringPausedUntil"
        static let historyMaximumAgeDays = "historyMaximumAgeDays"
        static let historyLimit = "historyLimit"
        static let maximumPayloadBytes = "maximumPayloadBytes"
        static let autoPasteEnabled = "autoPasteEnabled"
        static let copyOnlyFallbackEnabled = "copyOnlyFallbackEnabled"
        static let pasteDelay = "pasteDelay"
        static let ignoreTransient = "ignoreTransient"
        static let ignoreConcealed = "ignoreConcealed"
        static let ignoreAutoGenerated = "ignoreAutoGenerated"
        static let ignoredBundleIdentifiers = "ignoredBundleIdentifiers"
        static let onboardingCompleted = "onboardingCompleted"
        static let launchAtLogin = "launchAtLogin"
        static let includeUniversalClipboard = "includeUniversalClipboard"
        static let panelAnchor = "panelAnchor"
        static let panelDensity = "panelDensity"
        static let keepSearchQuery = "keepSearchQuery"
        static let showDockIcon = "showDockIcon"
    }

    private let defaults: UserDefaults
    private var resumeTimer: Timer?
    private var isResetting = false
    var monitoringEnabled: Bool {
        didSet {
            if monitoringPausedUntil != nil { monitoringPausedUntil = nil }
            defaults.set(monitoringEnabled, forKey: Key.monitoringEnabled)
            onMonitoringChanged?(monitoringEnabled)
        }
    }
    private(set) var monitoringPausedUntil: Date? {
        didSet {
            if let monitoringPausedUntil { defaults.set(monitoringPausedUntil, forKey: Key.monitoringPausedUntil) }
            else { defaults.removeObject(forKey: Key.monitoringPausedUntil) }
            scheduleAutomaticResume()
            onMonitoringChanged?(monitoringEnabled)
        }
    }
    /// Zero disables age expiry. Pinned and deliberately saved library items never expire.
    var historyMaximumAgeDays: Int {
        didSet {
            let validated = SettingsValidation.historyMaximumAgeDays(historyMaximumAgeDays)
            guard historyMaximumAgeDays == validated else { historyMaximumAgeDays = validated; return }
            defaults.set(historyMaximumAgeDays, forKey: Key.historyMaximumAgeDays)
            if !isResetting { onRetentionChanged?() }
        }
    }
    var historyLimit: Int {
        didSet {
            let validated = SettingsValidation.historyLimit(historyLimit)
            guard historyLimit == validated else { historyLimit = validated; return }
            defaults.set(historyLimit, forKey: Key.historyLimit)
            if !isResetting { onRetentionChanged?() }
        }
    }
    var maximumPayloadBytes: Int {
        didSet {
            let validated = SettingsValidation.maximumPayloadBytes(maximumPayloadBytes)
            guard maximumPayloadBytes == validated else { maximumPayloadBytes = validated; return }
            defaults.set(maximumPayloadBytes, forKey: Key.maximumPayloadBytes)
        }
    }
    var autoPasteEnabled: Bool { didSet { defaults.set(autoPasteEnabled, forKey: Key.autoPasteEnabled) } }
    var copyOnlyFallbackEnabled: Bool { didSet { defaults.set(copyOnlyFallbackEnabled, forKey: Key.copyOnlyFallbackEnabled) } }
    var pasteDelay: Double {
        didSet {
            let validated = SettingsValidation.pasteDelay(pasteDelay)
            guard pasteDelay == validated else { pasteDelay = validated; return }
            defaults.set(pasteDelay, forKey: Key.pasteDelay)
        }
    }
    var ignoreTransient: Bool { didSet { defaults.set(ignoreTransient, forKey: Key.ignoreTransient) } }
    var ignoreConcealed: Bool { didSet { defaults.set(ignoreConcealed, forKey: Key.ignoreConcealed) } }
    var ignoreAutoGenerated: Bool { didSet { defaults.set(ignoreAutoGenerated, forKey: Key.ignoreAutoGenerated) } }
    var ignoredBundleIdentifiers: Set<String> { didSet { defaults.set(Array(ignoredBundleIdentifiers), forKey: Key.ignoredBundleIdentifiers) } }
    var onboardingCompleted: Bool { didSet { defaults.set(onboardingCompleted, forKey: Key.onboardingCompleted) } }
    var launchAtLogin: Bool { didSet { defaults.set(launchAtLogin, forKey: Key.launchAtLogin) } }
    var includeUniversalClipboard: Bool { didSet { defaults.set(includeUniversalClipboard, forKey: Key.includeUniversalClipboard) } }
    var panelAnchor: PanelAnchor { didSet { defaults.set(panelAnchor.rawValue, forKey: Key.panelAnchor) } }
    var panelDensity: PanelDensity { didSet { defaults.set(panelDensity.rawValue, forKey: Key.panelDensity) } }
    var keepSearchQuery: Bool { didSet { defaults.set(keepSearchQuery, forKey: Key.keepSearchQuery) } }
    var showDockIcon: Bool { didSet { defaults.set(showDockIcon, forKey: Key.showDockIcon); onDockIconVisibilityChanged?(showDockIcon) } }
    var onMonitoringChanged: ((Bool) -> Void)?
    var onRetentionChanged: (() -> Void)?
    var onDockIconVisibilityChanged: ((Bool) -> Void)?

    init(defaults: UserDefaults = .standard) {
        self.defaults = defaults
        let savedPause = defaults.object(forKey: Key.monitoringPausedUntil) as? Date
        monitoringPausedUntil = savedPause
        monitoringEnabled = defaults.object(forKey: Key.monitoringEnabled) as? Bool ?? false
        historyMaximumAgeDays = SettingsValidation.historyMaximumAgeDays(defaults.object(forKey: Key.historyMaximumAgeDays) as? Int ?? 0)
        historyLimit = SettingsValidation.historyLimit(defaults.object(forKey: Key.historyLimit) as? Int ?? 500)
        maximumPayloadBytes = SettingsValidation.maximumPayloadBytes(defaults.object(forKey: Key.maximumPayloadBytes) as? Int ?? 20 * 1_024 * 1_024)
        autoPasteEnabled = defaults.object(forKey: Key.autoPasteEnabled) as? Bool ?? true
        copyOnlyFallbackEnabled = defaults.object(forKey: Key.copyOnlyFallbackEnabled) as? Bool ?? true
        pasteDelay = SettingsValidation.pasteDelay(defaults.object(forKey: Key.pasteDelay) as? Double ?? 0.10)
        ignoreTransient = defaults.object(forKey: Key.ignoreTransient) as? Bool ?? true
        ignoreConcealed = defaults.object(forKey: Key.ignoreConcealed) as? Bool ?? true
        ignoreAutoGenerated = defaults.object(forKey: Key.ignoreAutoGenerated) as? Bool ?? true
        ignoredBundleIdentifiers = Set(defaults.stringArray(forKey: Key.ignoredBundleIdentifiers) ?? [])
        onboardingCompleted = defaults.object(forKey: Key.onboardingCompleted) as? Bool ?? false
        launchAtLogin = defaults.object(forKey: Key.launchAtLogin) as? Bool ?? false
        includeUniversalClipboard = defaults.object(forKey: Key.includeUniversalClipboard) as? Bool ?? true
        panelAnchor = PanelAnchor(rawValue: defaults.string(forKey: Key.panelAnchor) ?? "") ?? .mousePointer
        panelDensity = PanelDensity(rawValue: defaults.string(forKey: Key.panelDensity) ?? "") ?? .comfortable
        keepSearchQuery = defaults.object(forKey: Key.keepSearchQuery) as? Bool ?? false
        showDockIcon = defaults.object(forKey: Key.showDockIcon) as? Bool ?? false
        if let savedPause {
            // A timed pause survives relaunch. A deadline passed while closed resumes on launch.
            if savedPause <= .now { resumeMonitoring() }
            else { monitoringEnabled = false; monitoringPausedUntil = savedPause }
        }
        scheduleAutomaticResume()
    }

    func pauseMonitoring(for duration: MonitoringPauseDuration, now: Date = .now) {
        guard monitoringEnabled || monitoringPausedUntil != nil else { return }
        monitoringEnabled = false
        monitoringPausedUntil = now.addingTimeInterval(duration.rawValue)
    }

    func resumeMonitoring() {
        monitoringEnabled = true
    }

    /// Called on wake as well as by the deadline timer, so sleep never extends a pause.
    func resumeMonitoringIfNeeded(now: Date = .now) {
        guard let deadline = monitoringPausedUntil, deadline <= now else { return }
        resumeMonitoring()
    }

    private func scheduleAutomaticResume() {
        resumeTimer?.invalidate()
        resumeTimer = nil
        guard let deadline = monitoringPausedUntil else { return }
        let timer = Timer(fire: deadline, interval: 0, repeats: false) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.resumeMonitoringIfNeeded()
                self?.scheduleAutomaticResume()
            }
        }
        resumeTimer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    func reset() {
        isResetting = true
        defer { isResetting = false }
        [
            Key.monitoringEnabled, Key.historyLimit, Key.maximumPayloadBytes, Key.autoPasteEnabled,
            Key.copyOnlyFallbackEnabled, Key.pasteDelay, Key.ignoreTransient, Key.ignoreConcealed,
            Key.ignoreAutoGenerated, Key.ignoredBundleIdentifiers, Key.onboardingCompleted,
            Key.launchAtLogin, Key.includeUniversalClipboard, Key.panelAnchor, Key.panelDensity,
            Key.keepSearchQuery, Key.showDockIcon, Key.monitoringPausedUntil, Key.historyMaximumAgeDays
        ].forEach(defaults.removeObject(forKey:))
        monitoringEnabled = false
        historyMaximumAgeDays = 0
        historyLimit = 500
        maximumPayloadBytes = 20 * 1_024 * 1_024
        autoPasteEnabled = true
        copyOnlyFallbackEnabled = true
        pasteDelay = 0.10
        ignoreTransient = true
        ignoreConcealed = true
        ignoreAutoGenerated = true
        ignoredBundleIdentifiers = []
        onboardingCompleted = false
        launchAtLogin = false
        includeUniversalClipboard = true
        panelAnchor = .mousePointer
        panelDensity = .comfortable
        keepSearchQuery = false
        showDockIcon = false
    }
}
