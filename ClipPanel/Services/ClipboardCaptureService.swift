import AppKit
import Foundation

enum ClipboardCaptureOutcome: Equatable {
    case captured(ClipboardCaptureCandidate)
    case ignored(ClipboardIgnoreReason)
}

enum ClipboardIgnoreReason: String, Equatable {
    case selfWrite
    case privacyMarker
    case ignoredApplication
    case unsupported
    case oversized
}

struct ClipboardCaptureFilteringPolicy: Sendable, Equatable {
    var ignoreTransient: Bool
    var ignoreConcealed: Bool
    var ignoreAutoGenerated: Bool
    var ignoredBundleIdentifiers: Set<String>
    var includeUniversalClipboard: Bool
}

struct ClipboardCaptureCandidate: Equatable {
    let payload: ClipboardPayload
    let encodedPayload: Data
    let preview: ClipboardPreview
    let contentHash: String
    let source: SourceApplication?
}

@MainActor
final class ClipboardCaptureService {
    func capture(from pasteboard: NSPasteboard, settings: SettingsStore, source: SourceApplication?) -> ClipboardCaptureOutcome {
        // Exclusions are evaluated before asking another app for any clipboard representation.
        if let identifier = source?.bundleIdentifier, settings.ignoredBundleIdentifiers.contains(identifier) {
            return .ignored(.ignoredApplication)
        }
        let items = pasteboard.pasteboardItems ?? []
        let policy = ClipboardCaptureFilteringPolicy(
            ignoreTransient: settings.ignoreTransient,
            ignoreConcealed: settings.ignoreConcealed,
            ignoreAutoGenerated: settings.ignoreAutoGenerated,
            ignoredBundleIdentifiers: settings.ignoredBundleIdentifiers,
            includeUniversalClipboard: settings.includeUniversalClipboard
        )
        if let reason = Self.filteringReason(
            itemTypeIdentifiers: items.map { Set($0.types.map(\.rawValue)) },
            policy: policy,
            sourceBundleIdentifier: source?.bundleIdentifier
        ) { return .ignored(reason) }

        let payloadItems = items.compactMap(snapshot)
        let payload = ClipboardPayload(items: payloadItems)
        guard !payload.items.isEmpty else { return .ignored(.unsupported) }
        guard !Self.exceedsPayloadLimit(byteCount: payload.byteCount, limit: settings.maximumPayloadBytes) else { return .ignored(.oversized) }
        guard let encodedPayload = try? JSONEncoder().encode(payload) else { return .ignored(.unsupported) }
        let preview = PreviewBuilder.build(payload: payload)
        return .captured(ClipboardCaptureCandidate(payload: payload, encodedPayload: encodedPayload, preview: preview, contentHash: ClipboardHasher.hash(payload: payload), source: source))
    }

    nonisolated static func filteringReason(itemTypeIdentifiers: [Set<String>], policy: ClipboardCaptureFilteringPolicy, sourceBundleIdentifier: String?) -> ClipboardIgnoreReason? {
        if itemTypeIdentifiers.contains(where: { $0.contains(ClipboardConstants.selfWriteMarker.rawValue) }) { return .selfWrite }
        if itemTypeIdentifiers.contains(where: {
            (policy.ignoreTransient && $0.contains(ClipboardConstants.transientMarker.rawValue)) ||
                (policy.ignoreConcealed && $0.contains(ClipboardConstants.concealedMarker.rawValue)) ||
                (policy.ignoreAutoGenerated && $0.contains(ClipboardConstants.autoGeneratedMarker.rawValue))
        }) { return .privacyMarker }
        if !policy.includeUniversalClipboard,
           itemTypeIdentifiers.contains(where: { $0.contains(ClipboardConstants.remoteClipboardMarker.rawValue) }) {
            return .privacyMarker
        }
        if let sourceBundleIdentifier, policy.ignoredBundleIdentifiers.contains(sourceBundleIdentifier) { return .ignoredApplication }
        return nil
    }

    nonisolated static func exceedsPayloadLimit(byteCount: Int, limit: Int) -> Bool {
        byteCount > limit
    }

    private func snapshot(_ item: NSPasteboardItem) -> ClipboardPayloadItem? {
        let representations = item.types.compactMap { type -> ClipboardRepresentation? in
            guard Self.isAllowed(type), let data = item.data(forType: type) else { return nil }
            return ClipboardRepresentation(typeIdentifier: type.rawValue, data: Data(data))
        }
        return representations.isEmpty ? nil : ClipboardPayloadItem(representations: representations)
    }

    static func isAllowed(_ type: NSPasteboard.PasteboardType) -> Bool {
        let allowed = [
            NSPasteboard.PasteboardType.string.rawValue,
            NSPasteboard.PasteboardType.html.rawValue,
            NSPasteboard.PasteboardType.rtf.rawValue,
            NSPasteboard.PasteboardType.png.rawValue,
            NSPasteboard.PasteboardType.tiff.rawValue,
            NSPasteboard.PasteboardType.fileURL.rawValue,
            NSPasteboard.PasteboardType.URL.rawValue,
            "public.utf8-plain-text",
            "public.plain-text"
        ]
        return allowed.contains(type.rawValue)
    }
}
