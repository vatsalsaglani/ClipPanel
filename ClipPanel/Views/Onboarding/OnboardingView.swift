import AppKit
import KeyboardShortcuts
import SwiftUI

struct OnboardingView: View {
    @Bindable var settings: SettingsStore
    let permissionService: PermissionService
    let finish: () -> Void
    @State private var page = 0
    @State private var autoPasteGranted = false
    @State private var autoPasteStatus = "Allow Accessibility access to paste into your previous app with Return."
    @State private var loginError: String?

    var body: some View {
        VStack(alignment: .leading, spacing: 20) {
            TabView(selection: $page) {
                welcome
                    .tabItem { Label("Welcome", systemImage: "clipboard") }
                    .tag(0)
                shortcut
                    .tabItem { Label("Shortcut", systemImage: "command") }
                    .tag(1)
                privacy
                    .tabItem { Label("Privacy", systemImage: "lock") }
                    .tag(2)
                finishPage
                    .tabItem { Label("Ready", systemImage: "checkmark.circle") }
                    .tag(3)
            }
            .tabViewStyle(.automatic)
            HStack {
                if page > 0 { Button("Back") { page -= 1 } }
                Spacer()
                Button(page == 3 ? "Start Using ClipPanel" : "Continue") {
                    advance()
                }
                .buttonStyle(.borderedProminent)
            }
        }
        .padding(28)
        .onAppear { refreshAutoPasteAccess() }
        .onReceive(NotificationCenter.default.publisher(for: NSApplication.didBecomeActiveNotification)) { _ in
            refreshAutoPasteAccess()
        }
        .onChange(of: settings.launchAtLogin) { _, enabled in
            do { try LaunchAtLoginService().setEnabled(enabled); loginError = nil }
            catch { loginError = "Launch at login could not be changed." }
        }
    }

    private var welcome: some View {
        VStack(alignment: .leading, spacing: 12) {
            Image(systemName: "clipboard.fill").font(.system(size: 42)).foregroundStyle(.tint)
            Text("Your clipboard, kept on your Mac").font(.title2.bold())
            Text("ClipPanel saves supported clipboard history locally so you can recover it quickly. Clipboard history may contain sensitive information. You can pause monitoring or clear history at any time.")
            Label("No accounts, analytics, cloud sync, or network access.", systemImage: "lock.fill")
                .foregroundStyle(.secondary)
        }
    }

    private var shortcut: some View {
        VStack(alignment: .leading, spacing: 16) {
            Text("Open ClipPanel quickly").font(.title2.bold())
            Text("Choose a global shortcut for the summon → search → paste loop. The local build starts with Control-Q when it is available; you can change or remove it later.")
            KeyboardShortcuts.Recorder("Show Clipboard:", name: .togglePanel)
        }
    }

    private var privacy: some View {
        VStack(alignment: .leading, spacing: 14) {
            Text("Choose permissions deliberately").font(.title2.bold())
            Toggle("Enable local clipboard monitoring", isOn: $settings.monitoringEnabled)
            Text("Monitoring reads the general pasteboard continuously while enabled. Entries with common transient, concealed, and autogenerated markers are ignored by default.")
                .foregroundStyle(.secondary)
            Toggle("Paste into the previous app with Return", isOn: $settings.autoPasteEnabled)
            if settings.autoPasteEnabled {
                Button(autoPasteGranted ? "Check Auto-Paste Permission" : "Allow Auto-Paste…") {
                    requestAutoPasteAccess()
                }
                Text(autoPasteStatus).font(.caption).foregroundStyle(.secondary)
                if !autoPasteGranted {
                    Button("Continue with Copy Only") {
                        settings.autoPasteEnabled = false
                        page = 3
                    }
                }
            } else {
                Text("Return will copy the selected item. Press Command-V in your destination app to paste.")
                    .font(.caption).foregroundStyle(.secondary)
            }
        }
    }

    private var finishPage: some View {
        VStack(alignment: .leading, spacing: 14) {
            Text(settings.autoPasteEnabled && !autoPasteGranted ? "Auto-paste needs permission" : "You’re ready")
                .font(.title2.bold())
            Toggle("Launch ClipPanel at login", isOn: $settings.launchAtLogin)
            if let loginError { Text(loginError).font(.caption).foregroundStyle(.secondary) }
            Text(settings.autoPasteEnabled
                 ? (autoPasteGranted
                    ? "Copy something, press your shortcut, type to search, then press Return to paste into your previous app."
                    : "Allow Accessibility access on the Privacy tab, or choose Copy Only, before finishing setup.")
                 : "Copy something, press your shortcut, type to search, then press Return to copy. Press Command-V in your destination app to paste.")
                .foregroundStyle(.secondary)
        }
    }

    private func refreshAutoPasteAccess() {
        autoPasteGranted = permissionService.autoPasteState == .granted
        autoPasteStatus = autoPasteGranted
            ? "Auto-paste permission is available."
            : "In System Settings → Privacy & Security → Accessibility, enable this copy of ClipPanel, then return here. macOS requires your approval."
    }

    private func requestAutoPasteAccess() {
        _ = permissionService.requestAutoPasteAccess(openSettingsIfNeeded: true)
        refreshAutoPasteAccess()
    }

    private func advance() {
        // Check at both boundaries: tabs can be selected directly, and macOS
        // permission may change while the onboarding window is open.
        if page >= 2, settings.autoPasteEnabled {
            refreshAutoPasteAccess()
            guard autoPasteGranted else {
                page = 2
                requestAutoPasteAccess()
                return
            }
        }
        if page == 3 {
            settings.onboardingCompleted = true
            finish()
        } else {
            page += 1
        }
    }

}
