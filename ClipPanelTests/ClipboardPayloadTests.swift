private func candidate(text: String) -> ClipboardCaptureCandidate {
    let payload = ClipboardPayload(items: [ClipboardPayloadItem(representations: [ClipboardRepresentation(typeIdentifier: "public.utf8-plain-text", data: Data(text.utf8))])])
    return ClipboardCaptureCandidate(
        payload: payload,
        encodedPayload: try! JSONEncoder().encode(payload),
        preview: ClipboardPreview(kind: .text, displayText: text, searchText: text),
        contentHash: ClipboardHasher.hash(payload: payload),
        source: nil
    )
}

