    func testV1HistoryMigratesToTheLibrarySchema() async throws {
        let count = try await MainActor.run { () throws -> Int in
            let directory = FileManager.default.temporaryDirectory.appendingPathComponent("ClipPanelMigrationTests.\(UUID().uuidString)", isDirectory: true)
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            defer { try? FileManager.default.removeItem(at: directory) }
            let configuration = ModelConfiguration(url: directory.appendingPathComponent("history.store"))
            let v1 = try ModelContainer(for: Schema(ClipboardSchemaV1.models), configurations: configuration)
            let v1Context = ModelContext(v1)
            let legacy = candidate(text: "before migration")
            v1Context.insert(ClipboardRecord(
                kind: legacy.preview.kind,
                displayText: legacy.preview.displayText,
                searchText: legacy.preview.searchText,
                contentHash: legacy.contentHash,
                byteCount: legacy.payload.byteCount,
                itemCount: legacy.payload.items.count,
                payloadData: legacy.encodedPayload
            ))
            try v1Context.save()

            let v2 = try ModelContainer(
                for: Schema(ClipboardSchemaV2.models),
                migrationPlan: ClipboardMigrationPlan.self,
                configurations: configuration
            )
            return try ClipboardStore(modelContext: ModelContext(v2), vault: try EncryptedPayloadVault(keyData: Data(repeating: 0, count: 32))).records().count
        }
        XCTAssertEqual(count, 1)
    }

    func testEncryptedCollectionRemovesPlainPayloadButKeepsClipUsable() async throws {
        let result = try await MainActor.run { () throws -> (Data, String?, Data) in
            let container = try ModelContainer(
                for: Schema(ClipboardSchemaV2.models),
                configurations: ModelConfiguration(isStoredInMemoryOnly: true)
            )
            let vault = try EncryptedPayloadVault(keyData: Data(repeating: 7, count: 32))
            let store = ClipboardStore(modelContext: ModelContext(container), vault: vault)
            let record = try store.upsert(candidate(text: "private clip"), historyLimit: 500)
            let collection = try store.createCollection(named: "Private", isEncrypted: true)
            _ = try store.updateMetadata(recordID: record.id, collectionIDs: [collection.id])
            let encryptedStorage = record.payloadData
            let usableText = PreviewBuilder.text(from: try store.payload(for: record))
            _ = try store.updateMetadata(recordID: record.id, collectionIDs: [])
            return (encryptedStorage, usableText, record.payloadData)
        }
        XCTAssertTrue(result.0.isEmpty)
        XCTAssertEqual(result.1, "private clip")
        XCTAssertFalse(result.2.isEmpty)
    }

    func testEncryptedArchiveRoundTripsRecordsAndMetadata() async throws {
        let result = try await MainActor.run { () throws -> (Bool, Int, [String]) in
            let sourceContainer = try ModelContainer(
                for: Schema(ClipboardSchemaV2.models),
                configurations: ModelConfiguration(isStoredInMemoryOnly: true)
            )
            let sourceStore = ClipboardStore(
                modelContext: ModelContext(sourceContainer),
                vault: try EncryptedPayloadVault(keyData: Data(repeating: 3, count: 32))
            )
            let record = try sourceStore.upsert(candidate(text: "archived secret"), historyLimit: 500)
            let tag = try sourceStore.createTag(named: "Important")
            _ = try sourceStore.updateMetadata(recordID: record.id, title: "Archive title", isSavedSnippet: true, tagIDs: [tag.id])
            let encrypted = try ClipArchiveService.exportData(from: sourceStore, password: "correct horse battery staple")

            let destinationContainer = try ModelContainer(
                for: Schema(ClipboardSchemaV2.models),
                configurations: ModelConfiguration(isStoredInMemoryOnly: true)
            )
            let destinationStore = ClipboardStore(
                modelContext: ModelContext(destinationContainer),
                vault: try EncryptedPayloadVault(keyData: Data(repeating: 4, count: 32))
            )
            let imported = try ClipArchiveService.importData(encrypted, into: destinationStore, password: "correct horse battery staple")
            return (ClipArchiveService.requiresPassword(for: encrypted), imported, try destinationStore.libraryItems().map(\.title))
        }
        XCTAssertTrue(result.0)
        XCTAssertEqual(result.1, 1)
        XCTAssertEqual(result.2, ["Archive title"])
    }

    func testCustomTextCommandCreatesASeparateTransformedClip() async throws {
        let result = try await MainActor.run { () throws -> [String] in
            let container = try ModelContainer(
                for: Schema(ClipboardSchemaV2.models),
                configurations: ModelConfiguration(isStoredInMemoryOnly: true)
            )
            let store = ClipboardStore(modelContext: ModelContext(container), vault: try EncryptedPayloadVault(keyData: Data(repeating: 5, count: 32)))
            let original = try store.upsert(candidate(text: "ticket-123"), historyLimit: 500)
            let command = CustomTextCommand(name: "Ticket prefix", find: "ticket-", replacement: "INC-")
            let transformed = try store.createTransformedRecord(from: original, command: command)
            return try [original, transformed].compactMap { $0 }.map { try PreviewBuilder.text(from: store.payload(for: $0)) ?? "" }
        }
        XCTAssertEqual(result, ["ticket-123", "INC-123"])
    }

