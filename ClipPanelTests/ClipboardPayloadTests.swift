import AppKit
import SwiftData
import XCTest
@testable import ClipPanel

final class ClipboardPayloadTests: XCTestCase {
    func testPayloadRoundTripPreservesMultipleItemsAndTypes() throws {
        let payload = ClipboardPayload(items: [
            ClipboardPayloadItem(representations: [
                ClipboardRepresentation(typeIdentifier: "public.utf8-plain-text", data: Data("first".utf8)),
                ClipboardRepresentation(typeIdentifier: "public.html", data: Data("<b>first</b>".utf8))
            ]),
            ClipboardPayloadItem(representations: [
                ClipboardRepresentation(typeIdentifier: "public.file-url", data: Data("file:///tmp/example.txt".utf8))
            ])
        ])

        XCTAssertEqual(try JSONDecoder().decode(ClipboardPayload.self, from: JSONEncoder().encode(payload)), payload)
    }

    func testCanonicalHashNormalizesRepresentationOrderButNotItemBoundaries() {
        let first = ClipboardPayload(items: [
            ClipboardPayloadItem(representations: [
                ClipboardRepresentation(typeIdentifier: "b", data: Data([2])),
                ClipboardRepresentation(typeIdentifier: "a", data: Data([1]))
            ])
        ])
        let reordered = ClipboardPayload(items: [
            ClipboardPayloadItem(representations: [
                ClipboardRepresentation(typeIdentifier: "a", data: Data([1])),
                ClipboardRepresentation(typeIdentifier: "b", data: Data([2]))
            ])
        ])
        let differentBoundary = ClipboardPayload(items: [
            ClipboardPayloadItem(representations: [ClipboardRepresentation(typeIdentifier: "a", data: Data([1]))]),
            ClipboardPayloadItem(representations: [ClipboardRepresentation(typeIdentifier: "b", data: Data([2]))])
        ])

        XCTAssertEqual(ClipboardHasher.hash(payload: first), ClipboardHasher.hash(payload: reordered))
        XCTAssertNotEqual(ClipboardHasher.hash(payload: first), ClipboardHasher.hash(payload: differentBoundary))
    }

